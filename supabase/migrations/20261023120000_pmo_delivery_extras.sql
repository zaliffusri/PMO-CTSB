-- Delivery extras: RAID, task links/comments, timesheet flags, SLA/CSAT, programs, knowledge

alter table public.projects add column if not exists program_name text;

alter table public.project_tasks add column if not exists predecessor_id bigint references public.project_tasks(id) on delete set null;

alter table public.task_time_sessions add column if not exists billable boolean not null default true;
alter table public.task_time_sessions add column if not exists approved_at timestamptz;
alter table public.task_time_sessions add column if not exists approved_by_user_id bigint;

alter table public.issues add column if not exists sla_hours numeric;
alter table public.issues add column if not exists sla_due_at timestamptz;
alter table public.issues add column if not exists csat_score integer;
alter table public.issues add column if not exists csat_comment text;

alter table public.backlogs_app add column if not exists approval_status text;
alter table public.backlogs_app add column if not exists approved_by_user_id bigint;
alter table public.backlogs_app add column if not exists approved_at timestamptz;
alter table public.backlogs_app add column if not exists approval_note text;

create table if not exists public.raid_items (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  kind text not null default 'risk',
  title text not null,
  description text,
  status text not null default 'open',
  impact text not null default 'medium',
  owner_person_id bigint,
  mitigation text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_raid_items_project on public.raid_items(project_id);

create table if not exists public.task_comments (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.project_tasks(id) on delete cascade,
  author_user_id bigint,
  body text not null,
  created_at timestamptz not null default now()
);
create index if not exists idx_task_comments_task on public.task_comments(task_id);

create table if not exists public.knowledge_articles (
  id bigint generated by default as identity primary key,
  title text not null,
  body text,
  module_code text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.project_activity (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  actor_name text,
  summary text not null,
  created_at timestamptz not null default now()
);
create index if not exists idx_project_activity_project on public.project_activity(project_id);
