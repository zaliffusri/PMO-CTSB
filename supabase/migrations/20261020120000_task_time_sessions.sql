-- Task work timers: accumulate actual_hours with one open session per person
create table if not exists public.task_time_sessions (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.project_tasks(id) on delete cascade,
  person_id bigint not null references public.people(id) on delete cascade,
  project_id bigint not null references public.projects(id) on delete cascade,
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  minutes integer,
  created_at timestamptz not null default now(),
  constraint task_time_sessions_minutes_check check (minutes is null or minutes >= 0),
  constraint task_time_sessions_ended_after_start check (ended_at is null or ended_at >= started_at)
);

create index if not exists idx_task_time_sessions_task_id on public.task_time_sessions(task_id);
create index if not exists idx_task_time_sessions_person_id on public.task_time_sessions(person_id);
create index if not exists idx_task_time_sessions_project_id on public.task_time_sessions(project_id);

-- At most one running timer per person
create unique index if not exists idx_task_time_sessions_one_open_per_person
  on public.task_time_sessions (person_id)
  where ended_at is null;

comment on table public.task_time_sessions is 'Work timer sessions for project tasks; open row (ended_at null) means currently timing';
